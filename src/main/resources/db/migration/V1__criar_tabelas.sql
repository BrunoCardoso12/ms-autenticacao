-- =====================================================================
-- MIGRATION V1: cria as tabelas iniciais.
--
-- Como o Flyway funciona:
--  - Ao subir, ele olha a tabela "flyway_schema_history" para saber quais scripts já rodaram.
--  - Roda, em ordem, só os que ainda não rodaram (V1, V2, V3...).
--  - Nome do arquivo: V<versão>__<descrição>.sql  (são DOIS underlines)
--
-- REGRA DE OURO: NUNCA altere um script que já rodou em produção.
-- Precisa mudar algo? Crie um novo, ex.: V2__adicionar_coluna_telefone.sql
-- (O Flyway guarda um checksum de cada script e acusa erro se um antigo for modificado.)
-- =====================================================================

CREATE TABLE usuarios (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255) NOT NULL,
    email    VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,          -- hash BCrypt
    role     VARCHAR(20)  NOT NULL,          -- USER | ADMIN
    enabled  BOOLEAN      NOT NULL
);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,  -- SHA-256 em hexadecimal = 64 caracteres
    usuario_id BIGINT      NOT NULL REFERENCES usuarios (id),
    expira_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    revogado   BOOLEAN     NOT NULL
);

CREATE TABLE tokens_verificacao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    usuario_id BIGINT      NOT NULL REFERENCES usuarios (id),
    tipo       VARCHAR(30) NOT NULL,         -- CONFIRMACAO_EMAIL | RECUPERACAO_SENHA
    expira_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    usado      BOOLEAN     NOT NULL
);

-- Índices nas chaves estrangeiras: deixam rápidas as buscas "tokens DESTE usuário"
-- (usadas no logout geral e ao invalidar tokens antigos)
CREATE INDEX idx_refresh_tokens_usuario     ON refresh_tokens (usuario_id);
CREATE INDEX idx_tokens_verificacao_usuario ON tokens_verificacao (usuario_id);
